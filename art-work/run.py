def done(i):
    sub = "bg" if i.startswith("bg_") else ("ui" if i in UI else "enemy")
    return os.path.exists(f"img/{sub}/{i}.webp")


def run(batch):
    todo = [i for i in BATCH[batch] if not done(i)]
    if not todo:
        return batch, "skip（ぜんぶ完成）"
    rows = []
    for i in todo:
        if i in UI:
            rows.append(f"- {i} | kind=ui（process.py ui で処理 → img/ui/{i}.webp） | {UI[i]}")
        elif i in E:
            n, boss, desc = E[i]
            rows.append(f"- {i} | kind=enemy | なまえ「{n}」| boss={'true' if boss else 'false'} | {desc}")
        else:
            rows.append(f"- {i} | kind=bg | {BG[i]}")
    ref = "art-work/sheets/pilot.png"
    ref_note = f"添付画像 {ref} が絵柄の基準です（パイロット）。同じ線・塗り・色の明るさで描いてください。" if os.path.exists(ref) else "これは最初のパイロットです。以後の全画像の基準になるので、絵柄のルールを特に丁寧に守ってください。"
    prompt = f"""art-work/BRIEF.md を読み、その通りに実行してください（計画だけで終わらず、画像生成 → process.py → コンタクトシート → 台帳まで完了すること）。
バッチ名: {batch}
生成するID（ぜんぶ）:
{chr(10).join(rows)}
{ref_note}
（kind=ui の画像は 主人公。添付の hero_ref.png の デザイン・配色を 必ず 守り、絵柄は パイロットと 同じ 太い輪郭の セル塗り にする。書き込み先は img/ui/ も 許可する。）"""
    cmd = ["codex", "exec", "--sandbox", "workspace-write", "-C", ROOT,
           "-c", 'model_reasoning_effort="medium"']
    if os.path.exists(ref):
        cmd += ["-i", ref]
    if any(i in UI for i in todo):
        cmd += ["-i", "art-work/ref/hero_ref.png"]
    if any(i.startswith("h_") for i in todo):
        cmd += ["-i", "art-work/ref/hero_style.png"]
    if "h_run3" in todo:
        cmd += ["-i", "art-work/ref/h_run_ref.png"]
    cmd += ["-"]
    with open(f"art-work/logs/{batch}.log", "w") as f:
        r = subprocess.run(cmd, input=prompt, text=True, stdout=f, stderr=subprocess.STDOUT)
    ok = sum(done(i) for i in todo)
    return batch, f"exit={r.returncode} {ok}/{len(todo)}"


batches = sys.argv[1:] or ["pilot"]
with cf.ThreadPoolExecutor(max_workers=4) as ex:
    for b, res in ex.map(run, batches):
        print(b, res, flush=True)
